/** 全部题目（展平，id = `essay-dayNN-qN`） */
export const ESSAY_QUESTIONS: EssayQuestion[] = Object.entries(BANK).flatMap(([levelId, seeds]) =>
  seeds.map(([tag, stem, options, answer, explanation], index) => ({
    id: `${levelId}-q${index + 1}`,
    levelId,
    tag,
    stem,
    options,
    answer,
    explanation,
  })),
);

export const essayQuestionById = new Map(ESSAY_QUESTIONS.map((question) => [question.id, question]));

/** 某关的完整题库（未打乱，供守卫与测试用） */
export function essayPoolOf(levelId: string): EssayQuestion[] {
  return ESSAY_QUESTIONS.filter((question) => question.levelId === levelId);
}

/* ---------- 下发用的确定性打乱：同一关每次打开题面一致，但与题库原文顺序不同 ---------- */

function hashString(text: string): number {
  let hash = 2166136261;
  for (let index = 0; index < text.length; index += 1) {
    hash ^= text.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function mulberry32(seed: number) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffled<T>(items: readonly T[], random: () => number): T[] {
  const list = [...items];
  for (let index = list.length - 1; index > 0; index -= 1) {
    const target = Math.floor(random() * (index + 1));
    [list[index], list[target]] = [list[target], list[index]];
  }
  return list;
}

export interface EssayQuizOption {
  /** 选项在题库里的原始下标——前端提交的是它，所以展示顺序打乱不影响判分 */
  key: number;
  text: string;
}

export interface EssayQuizItem {
  id: string;
  tag: string;
  stem: string;
  options: EssayQuizOption[];
}

/**
 * 下发给前端的一关题目：从 6 道里取 5 道，题序与选项顺序都按 levelId 确定性打乱。
 * 刻意不返回 answer 与 explanation——交卷后才由 gradeEssayQuiz 回传。
 */
export function essayQuizOf(levelId: string): EssayQuizItem[] {
  const pool = essayPoolOf(levelId);
  if (pool.length === 0) return [];
  const random = mulberry32(hashString(`essay-quiz:${levelId}`));
  return shuffled(pool, random)
    .slice(0, Math.min(ESSAY_QUIZ_SIZE, pool.length))
    .map((question) => ({
      id: question.id,
      tag: question.tag,
      stem: question.stem,
      options: shuffled(
        question.options.map((text, key) => ({ key, text })),
        random,
      ),
    }));
}

/** 本关本次下发的题目 id（判断「是否答完」用） */
export function essayQuizIds(levelId: string): string[] {
  return essayQuizOf(levelId).map((item) => item.id);
}

export interface EssayAnswer {
  id: string;
  key: number;
}

/** 交卷前的完整性校验：返回问题描述，null 表示可以判分 */
export function essayQuizIssue(levelId: string, answers: readonly EssayAnswer[]): string | null {
  const served = essayQuizOf(levelId);
  if (served.length === 0) return "本关没有配置客观题";
  const seen = new Set<string>();
  for (const answer of answers) {
    if (seen.has(answer.id)) return "同一道题重复作答";
    seen.add(answer.id);
    const question = essayQuestionById.get(answer.id);
    if (!question || question.levelId !== levelId) return "提交了不属于本关的题目";
    if (!Number.isInteger(answer.key) || answer.key < 0 || answer.key >= question.options.length)
      return "选项下标越界";
  }
  const missing = served.filter((item) => !seen.has(item.id));
  if (missing.length > 0) return `还有 ${missing.length} 道客观题未作答`;
  return null;
}

export interface EssayQuizMark {
  id: string;
  correct: boolean;
  /** 正确答案在原始选项里的下标（前端按本地选项的 key 定位文字） */
  answerKey: number;
  explanation: string;
}

export interface EssayQuizResult {
  correct: number;
  total: number;
  marks: EssayQuizMark[];
}

/**
 * 判分：以下发的题目为准（漏答即错），返回每题对错、正确答案与解析。
 * 只存作答、解析与对错现算——题库改文案时不会出现「库里存着旧解析」的两处漂移。
 */
export function gradeEssayQuiz(levelId: string, answers: readonly EssayAnswer[]): EssayQuizResult {
  const given = new Map(answers.map((answer) => [answer.id, answer.key]));
  const marks = essayQuizOf(levelId).map((item) => {
    const question = essayQuestionById.get(item.id) as EssayQuestion;
    return {
      id: item.id,
      correct: given.get(item.id) === question.answer,
      answerKey: question.answer,
      explanation: question.explanation,
    };
  });
  return {
    correct: marks.filter((mark) => mark.correct).length,
    total: marks.length,
    marks,
  };
}
