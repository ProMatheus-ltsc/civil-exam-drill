export const essayLevelById = new Map(ESSAY_LEVELS.map((level) => [level.id, level]));

/** 一关的预计用时（各实操任务之和，分钟） */
export function essayMinutes(level: EssayLevel): number {
  return level.tasks.reduce((sum, task) => sum + task.minutes, 0);
}

/**
 * 逐关解锁：第一关是入口，其余关卡要求上一关已通关（≥1 星）。
 * 与专项训练的「前置模块通关才解锁」同构，只是这里的前置固定为上一关。
 */
export function essayUnlocked(
  levelId: string,
  starsOf: (id: string) => number,
): boolean {
  const index = ESSAY_LEVELS.findIndex((level) => level.id === levelId);
  if (index <= 0) return index === 0;
  return starsOf(ESSAY_LEVELS[index - 1].id) >= 1;
}

export function essayStageOf(level: EssayLevel): EssayStage {
  return ESSAY_STAGES.find((stage) => stage.id === level.stage) as EssayStage;
}

/** 上一关（用于「需先通关：X」提示） */
export function essayPreviousLevel(level: EssayLevel): EssayLevel | null {
  const index = ESSAY_LEVELS.findIndex((item) => item.id === level.id);
  return index > 0 ? ESSAY_LEVELS[index - 1] : null;
}
